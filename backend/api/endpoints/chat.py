"""
FastAPI Endpoints for Chat, Ask, Simulate, Report, Anomaly.
"""
from fastapi import APIRouter, Depends, HTTPException, BackgroundTasks
from pydantic import BaseModel
from typing import Dict, Any, Optional
from security.auth import get_current_user
from agents.graph import enterprise_graph
import uuid
import structlog

logger = structlog.get_logger("enterprise_backend.api.chat")
router = APIRouter()

class ChatRequest(BaseModel):
    query: str
    intent: Optional[str] = None
    session_id: Optional[str] = None

class ChatResponse(BaseModel):
    session_id: str
    response: Dict[str, Any]

from api_contract import AskResponse, ResponseMetadata, TraceStep, ChartSpec

@router.post("/ask", response_model=ChatResponse)
@router.post("/chat", response_model=ChatResponse)
async def ask_endpoint(
    request: ChatRequest,
    background_tasks: BackgroundTasks,
    current_user: dict = Depends(get_current_user)
):
    """
    Standard query endpoint for invoking the LangGraph multi-agent orchestrator.
    """
    session_id = request.session_id or str(uuid.uuid4())
    logger.info("Received chat request", session_id=session_id, user=current_user["username"])
    
    # Initialize state
    state = {
        "question": request.query,
        "intent": request.intent or "data",
        "session_id": session_id,
        "metadata": {"user": current_user["username"]},
        "trace": [],
        "telemetry": [],
    }
    
    try:
        # Execute the graph
        config = {"configurable": {"thread_id": session_id}}
        result = enterprise_graph.invoke(state, config=config)
        
        # Map raw graph state to proper AskResponse schema expected by frontend
        meta = result.get("metadata", {})
        conf = result.get("confidence", 0.95)
        conf_label = "High" if conf >= 0.8 else "Medium" if conf >= 0.5 else "Low"
        
        trace_steps = []
        for t in result.get("trace", []):
            # Parse trace strings into TraceStep objects if needed, 
            # or just default to System agent
            trace_steps.append(TraceStep(
                agent="LangGraph",
                action=str(t),
                duration_sec=0.1
            ))
            
        chart_data = result.get("charts")[0] if result.get("charts") else None
        chart_spec = None
        if chart_data:
            chart_spec = ChartSpec(
                chart_type=chart_data.get("chart_type", chart_data.get("type", "bar")),
                title=chart_data.get("title", ""),
                data=chart_data.get("data", {}),
                layout=chart_data.get("layout", {})
            )
            
        ask_response = AskResponse(
            answer=result.get("narrative") or "No response generated by agents.",
            confidence=conf,
            confidence_label=conf_label,
            confidence_reason=f"Validation Status: {result.get('validation_status', 'Unknown')}",
            chart_spec=chart_spec,
            trace=trace_steps,
            approval_required=False,
            low_sample_size=False,
            is_out_of_scope=False,
            is_degraded=False,
            metadata=ResponseMetadata(
                records_analyzed=meta.get("records_analyzed", 0),
                processing_time_sec=meta.get("processing_time_sec", 0.0),
                agents_invoked=meta.get("agents_invoked", []),
                steps_taken=meta.get("steps_taken", 0),
                llm_provider=meta.get("llm_provider", "local"),
                model_used=meta.get("model_used", "unknown")
            )
        )
        
        return ChatResponse(
            session_id=session_id,
            response=ask_response.model_dump()
        )
    except Exception as e:
        logger.error("Graph execution failed", session_id=session_id, error=str(e))
        raise HTTPException(status_code=500, detail=f"Execution failed: {str(e)}")

# Add stub endpoints for /simulate, /report, /anomaly which simply override intent
@router.post("/simulate", response_model=ChatResponse)
async def simulate_endpoint(request: ChatRequest, current_user: dict = Depends(get_current_user)):
    request.intent = "simulate"
    return await ask_endpoint(request, BackgroundTasks(), current_user)

@router.post("/report", response_model=ChatResponse)
async def report_endpoint(request: ChatRequest, current_user: dict = Depends(get_current_user)):
    request.intent = "report"
    return await ask_endpoint(request, BackgroundTasks(), current_user)

@router.post("/anomaly", response_model=ChatResponse)
async def anomaly_endpoint(request: ChatRequest, current_user: dict = Depends(get_current_user)):
    request.intent = "risk"
    return await ask_endpoint(request, BackgroundTasks(), current_user)
